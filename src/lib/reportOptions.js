export const SHARE_NOTICE = "This report contains your health information. Only share it with people you trust.";

export const REPORT_FOOTER = "Generated by Levli from patient-entered data. Not a substitute for medical advice.";

const STORE_KEY = "levli_report_prefs";

export function loadReportPrefs() {
  try {
    const raw = localStorage.getItem(STORE_KEY);
    const parsed = raw ? JSON.parse(raw) : null;
    return parsed && typeof parsed === "object" && !Array.isArray(parsed) ? parsed : {};
  } catch {
    return {};
  }
}

export function saveReportPrefs(prefs) {
  try {
    localStorage.setItem(STORE_KEY, JSON.stringify(prefs));
  } catch {
    /* private mode / storage full — preferences are simply not remembered */
  }
}

/** Section list for a saved selection, core first. Anything unusable falls back to core. */
export function normaliseSections(selected) {
  const list = Array.isArray(selected) ? selected : [];
  return [...CORE_IDS, ...OPTIONAL_IDS.filter((id) => list.includes(id))];
}